"""Create the manufacturer Ed25519 key once and export its public key to C."""
from __future__ import annotations

import argparse
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser()
    parser.add_argument("--private", type=Path,
                        default=root / "产品表" / "签名密钥" / "manufacturer_ed25519_private.pem")
    parser.add_argument("--header", type=Path,
                        default=root / "bootloader" / "Boot" / "Inc" / "boot_signing_public_key.h")
    args = parser.parse_args()

    args.private.parent.mkdir(parents=True, exist_ok=True)
    if args.private.exists():
        private = serialization.load_pem_private_key(args.private.read_bytes(), password=None)
        if not isinstance(private, Ed25519PrivateKey):
            raise ValueError("签名私钥不是 Ed25519 格式")
        created = False
    else:
        private = Ed25519PrivateKey.generate()
        args.private.write_bytes(private.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        ))
        created = True

    public = private.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw
    )
    values = ",".join(f"0x{value:02X}U" for value in public)
    header = (
        "#ifndef BOOT_SIGNING_PUBLIC_KEY_H\n"
        "#define BOOT_SIGNING_PUBLIC_KEY_H\n\n"
        "/* Generated by key_management.py.  The private key never enters firmware. */\n"
        f"static const unsigned char g_boot_signing_public_key[32] = {{{values}}};\n\n"
        "#endif\n"
    )
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header, encoding="ascii")
    (args.private.parent / "manufacturer_ed25519_public.bin").write_bytes(public)
    print("已创建新厂家签名密钥。" if created else "已使用现有厂家签名密钥。")
    print(f"私钥：{args.private}")
    print(f"公钥头文件：{args.header}")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, FileNotFoundError, TypeError) as error:
        raise SystemExit(f"错误：{error}")
